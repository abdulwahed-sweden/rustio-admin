// Generates rio-admin-standalone.html: same page as rio-admin.html with the two
// local stylesheets inlined into a <style> block. Fonts + Bootstrap Icons stay on CDN.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const read = (f) => readFileSync(join(dir, f), 'utf8');

const tokens = read('rio-tokens.css');
const admin = read('rio-admin.css');
let html = read('rio-admin.html');

const inline = `<!-- Inlined from rio-tokens.css + rio-admin.css (generated by build-standalone.mjs) -->
<style>
${tokens}
${admin}
</style>`;

// Replace the two local <link rel="stylesheet" href="rio-*.css"> tags with the inline block.
html = html
  .replace(/<link rel="stylesheet" href="rio-tokens\.css">\s*\n\s*<link rel="stylesheet" href="rio-admin\.css">/, inline)
  .replace('<title>RustIO UI — Admin</title>', '<title>RustIO UI — Admin (standalone)</title>');

writeFileSync(join(dir, 'rio-admin-standalone.html'), html);
console.log('wrote rio-admin-standalone.html', html.length, 'bytes');
